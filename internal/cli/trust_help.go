// 実行ファイルだけを渡された場合も、外部文書なしで対処を判断できるようにする。
const trustRepositoryHelp = `
制限付き実行環境で信頼先を確認できない場合:
  trust_repository_unreadable は確認不能（unknown・終了コード2）。権限不足や原因未確認を成功扱いにしない。
  Gitがルートを取得できても、指定先・親・リンク先の実体を参照できるとは限らない。
  Gitの起動、対象の読取・列挙、Git管理領域の読取、パス要素とリンク先の実体参照が必要。
  begin だけは .workscope/ への作成・保存も必要。Git設定・インデックスへの書込は不要。

対処の順序:
  1. 所有者と内容を確認したGitルート1件を指定し、check --verbose で確認段階と原因区分を見る。
     原因区分が未確認なら、拒否したパス要素やAPIを断定しない。
  2. 対象と操作を実行環境が承認する実行経路が使える場合だけ、その経路で読み取り専用 check を比較する。
     同じ実行ファイル・作業場所・Gitルート・タスク名・引数を使う。自動で権限昇格や再試行はしない。
     baseline_missing は信頼先確認の通過だけを示す。begin の保存や全対象の走査の成功は未確認。
  3. 開始記録がない場合は、編集前の begin を確認できる実行経路で実行する。
     終了コード0・status=recorded・baseline_id を確認するまで編集を始めない。
     既存の開始記録は取り直さず、同じ記録で check する。作業後の check でも同じ確認可能な経路を使う。
  4. 承認された実行経路が使えない、または記録・照合を確認できなければ停止する。
     編集後に作った記録で過去の変更を検証済みにしない。既に編集していた場合は、
     編集前に取得していたGit状態と差分を手動で照合し、workscopeによる照合は未確認と報告する。

実行例（対象のGitルートへ移動し、信頼先・タスク名・許容範囲を実際の作業に合わせる）:
  workscope check --task '今回の作業' --trust-repository 'D:\作業\対象プロジェクト' --json-summary --verbose --no-progress
  未記録のタスクを診断に使った場合の baseline_missing は意図した終了コード2。
  承認された経路で、新しい作業を編集前に開始する場合だけ次を実行する:
  workscope begin --task '今回の作業' --allow src --trust-repository 'D:\作業\対象プロジェクト' --json-summary --no-progress
  作業後は同じタスクの check を実行し、終了コードと status を確認する。

権限や隔離を一括解除しない。safe.directory=*、別ルートへの自動切替、診断目的の --replace は使わない。
実体確認をパス文字列の一致で代用しない。開始記録とGit設定を手動で正常扱いに変更しない。
`
